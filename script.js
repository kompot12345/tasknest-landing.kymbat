// Функция приветствия пользователя
function helloUser(name) {
    // Показываем окно с приветствием и вставляем имя
    alert("Привет, " + name + "!");
}

// Спрашиваем имя у пользователя
const userName = prompt("Введите ваше имя:");
// Запускаем функцию приветствия с введенным именем
helloUser(userName);


// Функция, которая возвращает сумму двух чисел
function sum(a, b) {
    // Возвращаем результат сложения
    return a + b;
}

// Спрашиваем у пользователя два числа и приводим их к Number
const a = Number(prompt("Введите первое число для суммы:"));
const b = Number(prompt("Введите второе число для суммы:"));
// Показываем результат сложения
alert("Сумма: " + sum(a, b));


// Стрелочная функция, которая возвращает квадрат числа
const square = num => num * num;

// Берём число от пользователя
const sqNum = Number(prompt("Введите число для квадрата:"));
// Показываем квадрат числа
alert("Квадрат вашего числа: " + square(sqNum));


// Функция, которая возвращает максимальное из двух чисел
function max(x, y) {
    // Тернарный оператор сравнивает два числа и возвращает большее
    return x > y ? x : y;
}

// Получаем два числа от пользователя
const x = Number(prompt("Введите число A для сравнения:"));
const y = Number(prompt("Введите число B для сравнения:"));
// Показываем большее число
alert("Большее число: " + max(x, y));


// Функция проверки правильности пароля
function checkPassword(pass1, pass2) {
    // Сравниваем два введённых пароля и возвращаем сообщение
    return pass1 === pass2 
        ? "Пароль совпадает!" 
        : "Пароль неверный!";
}

// Пользователь придумывает и повторно вводит пароль
const pass1 = prompt("Придумайте пароль:");
const pass2 = prompt("Введите пароль ещё раз:");
// Показываем результат проверки
alert(checkPassword(pass1, pass2));


// Стрелочная функция, которая объединяет имя и фамилию
const getFullName = (first, last) => first + " " + last;

// Получаем имя и фамилию
const first = prompt("Введите ваше имя:");
const last = prompt("Введите вашу фамилию:");
// Показываем полное имя
alert("Полное имя: " + getFullName(first, last));


// Стрелочная функция, которая проверяет четность числа
const isEven = number => number % 2 === 0;

// Получаем число от пользователя
const numberCheck = Number(prompt("Введите число для проверки четности:"));
// Показываем четное или нечетное число
alert(isEven(numberCheck) ? "Число четное" : "Число нечетное");
